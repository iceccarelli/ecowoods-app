#!/usr/bin/env node
/**
 * scripts/geo-ingest.mjs — re-runnable, offline-first geo ingestion.
 *
 *   pnpm geo:ingest -- --ca-csv FILE --us-json FILE[,FILE] --retrieved 2026-10-25 [--write]
 *   pnpm geo:ingest -- --wds-csv-dir DIR --us-json FILE[,FILE] --retrieved D [--write]   # Canada from Web Data Service CSVs (DIR/<pid>.csv)
 *   pnpm geo:ingest -- --regenerate [--write]    # facts → market-inputs.generated.json only
 *   pnpm geo:ingest -- --ca-csv FILE --discover  # list candidate CSDs for unmapped CA markets
 *   pnpm geo:ingest -- --fetch-us --retrieved D  # pull ACS from api.census.gov (approved API)
 *
 * Inputs are the official downloads (see geo-sources.mjs). --retrieved is the
 * date the file was downloaded and is required: the date is a fact about the
 * file, so this script will not invent it. Crosswalk ids are checked against
 * the official name in the file; a mismatch skips the market and says so.
 * Output is deterministic (sorted, stable), so re-running on the same inputs
 * changes nothing. The production build reads only the committed JSON.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateFacts, validateCrosswalk, deriveInputs, METHOD_VERSION } from './geo-lib.mjs';
import { readCensusProfile, fileLines, readAcs, caFacts, usFacts, US_VARIABLES } from './geo-sources.mjs';
import { WDS_TABLES, readWdsCube, wdsFacts } from './geo-wds.mjs';

const ROOT = process.cwd();
const GEO = join(ROOT, 'apps/web/content/geo');
export const FACTS_PATH = join(GEO, 'sourced-facts.json');
export const MAP_PATH = join(GEO, 'geography-map.json');
export const OUT_PATH = join(GEO, 'market-inputs.generated.ts');

const stable = (o) => JSON.stringify(o, null, 2) + '\n';
/** The generated module: JSON values in a typed const, so no JSON-import loader is needed anywhere. */
export const renderGenerated = (g) =>
  `/* GENERATED by scripts/geo-ingest.mjs from sourced-facts.json + geography-map.json.\n` +
  ` * Do not edit by hand: verify:geodata fails if this drifts from the facts. */\n` +
  `import type { GeneratedInput } from './market-inputs';\n\n` +
  `export const GENERATED_METHOD_VERSION = ${g.methodVersion};\n` +
  `export const GENERATED_FACTS_SHA256 = '${g.factsSha256}';\n\n` +
  `export const GENERATED_INPUTS: Record<string, Record<string, GeneratedInput>> = ${JSON.stringify(g.inputs, null, 2)};\n`;
const sha = (s) => createHash('sha256').update(s).digest('hex');

export function buildGenerated(factsDoc, map, markets) {
  const { inputs, missing } = deriveInputs(factsDoc.facts, map, markets, { methodVersion: METHOD_VERSION });
  return {
    doc: {
      methodVersion: METHOD_VERSION,
      factsSha256: sha(JSON.stringify(factsDoc.facts)),
      inputs,
    },
    missing,
  };
}

const arg = (a, k) => (a.includes(k) ? a[a.indexOf(k) + 1] : null);

async function main() {
  const a = process.argv.slice(2).filter((x) => x !== '--');
  const write = a.includes('--write');
  const retrieved = arg(a, '--retrieved');
  const { MARKETS } = await import(join(GEO, 'markets.ts'));
  const markets = MARKETS.map(({ slug, country, kind, partOf }) => ({ slug, country, kind, partOf }));
  const map = JSON.parse(readFileSync(MAP_PATH, 'utf8'));
  const cwErrs = validateCrosswalk(map, markets);
  if (cwErrs.length) { console.error(cwErrs.join('\n')); process.exit(1); }

  const doc = JSON.parse(readFileSync(FACTS_PATH, 'utf8'));
  const report = [];
  let facts = doc.facts;
  const caFile = arg(a, '--ca-csv');
  const usFiles = arg(a, '--us-json');
  const wdsDir = arg(a, '--wds-csv-dir');

  if (a.includes('--discover')) {
    if (usFiles) {
      /* Candidates only: a person (or a reviewed change) decides, nothing is written. */
      const want = markets.filter((m) => m.country === 'US' && map.markets[m.slug].unmapped).map((m) => [m.slug, MARKETS.find((x) => x.slug === m.slug).name]);
      for (const f of usFiles.split(',')) {
        for (const [geoid, row] of readAcs(JSON.parse(readFileSync(f, 'utf8')))) {
          for (const [slug, name] of want) if (row.name.startsWith(`${name} `)) console.log(`${slug}\t${geoid}\t${row.name}`);
        }
      }
    }
    if (!caFile) { if (!usFiles) { console.error('--discover needs --ca-csv and/or --us-json'); process.exit(1); } return; }
    const want = new Map(markets.filter((m) => m.country === 'CA' && map.markets[m.slug].unmapped).map((m) => [m.slug, MARKETS.find((x) => x.slug === m.slug).name]));
    const names = new Set(want.values());
    let col = null;
    const seen = new Set();
    for await (const line of fileLines(caFile)) {
      const { parseCsvLine } = await import('./geo-sources.mjs');
      const c = parseCsvLine(line);
      if (!col) { col = Object.fromEntries(c.map((h, i) => [h.replace(/^﻿/, '').trim(), i])); continue; }
      const key = c[col.ALT_GEO_CODE];
      if (seen.has(key) || !names.has(c[col.GEO_NAME])) continue;
      seen.add(key);
      console.log(`${c[col.GEO_NAME]}\t${key}\t${c[col.GEO_LEVEL] ?? ''}\t${c[col.DGUID] ?? ''}`);
    }
    return;
  }

  if (caFile || usFiles || wdsDir || a.includes('--fetch-us')) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(retrieved ?? '')) { console.error('--retrieved YYYY-MM-DD (the date the file was downloaded) is required'); process.exit(1); }
    if (retrieved > new Date().toISOString().slice(0, 10)) { console.error('--retrieved is in the future'); process.exit(1); }
    const fresh = [];
    if (caFile) {
      const want = new Set(Object.values(map.markets).filter((e) => e.direct?.system === 'statcan-csd').map((e) => e.direct.id));
      fresh.push(...caFacts(await readCensusProfile(fileLines(caFile), want), map, markets, retrieved, report));
    }
    if (wdsDir) {
      const want = new Set(Object.values(map.markets).filter((e) => e.direct?.system === 'statcan-csd').map((e) => e.direct.id));
      const reads = [];
      for (const table of WDS_TABLES) reads.push({ table, result: await readWdsCube(fileLines(join(wdsDir, `${table.pid}.csv`)), table, want) });
      for (const r of reads) for (const n of r.result.notes) report.push(`${r.table.pid} ${n}`);
      fresh.push(...wdsFacts(reads, map, markets, retrieved, report));
    }
    const acs = [];
    if (usFiles) for (const f of usFiles.split(',')) acs.push(readAcs(JSON.parse(readFileSync(f, 'utf8'))));
    if (a.includes('--fetch-us')) {
      for (const level of ['place:*&in=state:36', 'county%20subdivision:*&in=state:36&in=county:*']) {
        const url = `https://api.census.gov/data/2024/acs/acs5?get=NAME,${US_VARIABLES.join(',')}&for=${level}`;
        const res = await fetch(url);
        if (!res.ok) { console.error(`ACS API ${res.status} for ${level}`); process.exit(1); }
        acs.push(readAcs(await res.json()));
      }
    }
    if (acs.length) fresh.push(...usFacts(acs, map, markets, retrieved, report));
    if (fresh.length === 0) { console.error(`no valid facts were extracted from the supplied file(s):\n${report.join('\n')}`); process.exit(1); }
    const replaced = new Set(fresh.map((f) => f.id));
    facts = [...doc.facts.filter((f) => !replaced.has(f.id)), ...fresh];
  }

  facts = [...facts].sort((x, y) => x.id.localeCompare(y.id));
  const next = { ...doc, note: doc.note, facts };
  const errs = validateFacts(next);
  if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
  const { doc: gen, missing } = buildGenerated(next, map, markets);

  const reportFile = arg(a, '--report');
  if (reportFile) writeFileSync(reportFile, [...report.map((r) => `SKIP ${r}`), ...missing.map((m) => `NOTE ${m}`)].join('\n') + '\n');
  for (const r of report) console.warn(`SKIP ${r}`);
  for (const m of missing) console.warn(`NOTE ${m}`);
  const covered = Object.keys(gen.inputs).length;
  console.log(`${facts.length} fact(s) valid; ${covered} market(s) carry derived inputs${write ? '' : ' (dry run, nothing written)'}`);
  if (write) {
    writeFileSync(FACTS_PATH, stable(next));
    writeFileSync(OUT_PATH, renderGenerated(gen));
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
