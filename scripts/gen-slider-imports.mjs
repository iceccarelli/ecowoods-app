#!/usr/bin/env node
/**
 * scripts/gen-slider-imports.mjs
 *
 * Writes apps/web/app/data/slider-images.ts — a static import per before/after
 * frame, exactly as gen-illustration-imports.mjs does for the diagrams.
 *
 * WHY, AND IT IS NOT A STYLE PREFERENCE
 *
 * This deployment does not serve apps/web/public. Measured, in audit/FINDINGS.md
 * F-131: /qr-app.jpg, which lives in the REPO-ROOT public/, returns 200, while
 * /icon-192.png, which has sat in apps/web/public since long before any of this
 * work, returns 404 — and so did every illustration written there.
 *
 * Both slider briefs specify URLs: `/images/sliders/<id>-after.webp` and
 * `/proof/<file>.webp`. On this host those are 404s. The zips would unzip
 * cleanly, git would commit 58 correct files, every source-reading guard would
 * pass, and the site would show 36 broken-image icons — which is F-131 word for
 * word, for the third time.
 *
 * data/floor-images.ts, data/machine-images.ts and data/illustration-images.ts
 * all carry this same workaround. 108 photographs and 135 diagrams render on
 * the live site precisely because they are imported rather than served.
 *
 *   node scripts/gen-slider-imports.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'apps/web/app/data/slider-images.ts');
const SOURCES = [
  { dir: 'apps/web/public/images/sliders', rel: '../../public/images/sliders' },
  { dir: 'apps/web/public/proof', rel: '../../public/proof' },
];

const frames = [];
for (const s of SOURCES) {
  const abs = path.join(ROOT, s.dir);
  if (!fs.existsSync(abs)) continue;
  for (const f of fs.readdirSync(abs).filter((f) => f.endsWith('.webp')).sort()) {
    frames.push({ key: f.replace(/\.webp$/, ''), spec: `${s.rel}/${f}` });
  }
}
if (!frames.length) {
  console.error('gen-slider-imports: no .webp found under either source directory.');
  process.exit(2);
}

const ident = (k) => 'f_' + k.replace(/[^a-z0-9]/gi, '_');
const body = `// AUTO-GENERATED by scripts/gen-slider-imports.mjs — do not edit by hand.
//
// Static imports for every before/after frame, so Next bundles them into
// _next/static instead of serving them from public/.
//
// THIS DEPLOYMENT DOES NOT SERVE apps/web/public. Measured, not assumed —
// audit/FINDINGS.md F-131. A URL like /images/sliders/01-...-after.webp is a
// 404 here no matter how correctly the file is committed. Both slider briefs
// specify exactly those URLs; this file is why the sliders render anyway.
//
// A static import also carries its own intrinsic width and height, so
// next/image reserves the right box and the two frames of a pair cannot
// disagree about their size without TypeScript noticing.
import type { StaticImageData } from 'next/image';

${frames.map((f) => `import ${ident(f.key)} from '${f.spec}';`).join('\n')}

export const SLIDER_FRAMES: Record<string, StaticImageData> = {
${frames.map((f) => `  '${f.key}': ${ident(f.key)},`).join('\n')}
};

export type SliderFrameKey = keyof typeof SLIDER_FRAMES;
`;
fs.writeFileSync(OUT, body);
console.log(`gen-slider-imports: ${frames.length} frame(s) → ${path.relative(ROOT, OUT)}`);
