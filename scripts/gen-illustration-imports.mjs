#!/usr/bin/env node
/**
 * scripts/gen-illustration-imports.mjs
 *
 * Regenerates app/data/illustration-images.ts from whatever is in
 * public/illustrations. Run it after adding or removing a diagram.
 *
 * WHY STATIC IMPORTS AND NOT public/ URLS
 *
 * This deployment does not serve apps/web/public. Measured, not assumed:
 * /qr-app.jpg — which lives in the REPO-ROOT public/ — returns 200, while
 * /icon-192.png, which has sat in apps/web/public since long before any of this
 * work, returns 404.
 *
 * data/floor-images.ts and data/machine-images.ts already carry this workaround
 * and state it in their first line. 108 photographs render on the live site
 * because they are bundled rather than served. The 28 diagrams were the only
 * images on the site that were not, and every one of them was a broken-image
 * icon in production while all fifteen guards passed.
 *
 *   node scripts/gen-illustration-imports.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'apps/web/public/illustrations');
const OUT = path.join(ROOT, 'apps/web/app/data/illustration-images.ts');

if (!fs.existsSync(DIR)) {
  console.error('gen-illustration-imports: apps/web/public/illustrations not found.');
  process.exit(2);
}

const ids = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith('.webp'))
  .map((f) => f.replace(/\.webp$/, ''))
  .sort();

const v = (id) => id.replace(/-/g, '_');

const header = `// AUTO-GENERATED by scripts/gen-illustration-imports.mjs — do not edit by hand.
//
// Static image imports, so Next bundles all ${ids.length} diagrams into
// _next/static rather than serving them from public/.
//
// WHY THIS FILE EXISTS AT ALL
//
// This deployment does not serve apps/web/public. Measured, not assumed:
// /qr-app.jpg — which lives in the REPO-ROOT public/ — returns 200, while
// /icon-192.png, which has sat in apps/web/public since long before any of this
// work, returns 404. So did every illustration written there.
//
// data/floor-images.ts and data/machine-images.ts already carry the same
// workaround and say so in their first line. 108 photographs render on the live
// site precisely because they are imported rather than served, and the 28
// diagrams were the only images on the site that were not.
//
// A static import also carries its own intrinsic width and height, so next/image
// reserves the correct box without the manifest having to declare it.
import type { StaticImageData } from 'next/image';

`;

let out = header;
for (const id of ids) out += `import ${v(id)} from '../../public/illustrations/${id}.webp';\n`;
out += `\nexport const ILLUSTRATION_IMAGES: Record<string, StaticImageData> = {\n`;
for (const id of ids) out += `  '${id}': ${v(id)},\n`;
out += `};\n\nexport const illustrationImage = (id: string): StaticImageData | undefined =>\n  ILLUSTRATION_IMAGES[id];\n`;

fs.writeFileSync(OUT, out);
console.log(`✓ generated ${ids.length} static import(s) → ${path.relative(ROOT, OUT)}`);
