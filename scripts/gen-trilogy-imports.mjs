#!/usr/bin/env node
/**
 * scripts/gen-trilogy-imports.mjs
 *
 * Regenerates apps/web/app/data/trilogy-images.ts from whatever is in
 * apps/web/public/images/trilogies/<slug>/0{1,2,3}.webp. Sibling of
 * scripts/gen-color-matching-imports.mjs — same reason, same shape: this
 * deployment does not serve apps/web/public (F-131), so every frame has to be
 * a static import, not a public/ URL, or it 404s in production while
 * genuinely sitting on disk and genuinely committed.
 *
 * Run after scripts/prepare-trilogy-images.mjs, or after adding/removing a
 * trilogy frame by hand.
 *
 *   node scripts/gen-trilogy-imports.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'apps/web/public/images/trilogies');
const OUT = path.join(ROOT, 'apps/web/app/data/trilogy-images.ts');

if (!fs.existsSync(DIR)) {
  console.error('gen-trilogy-imports: apps/web/public/images/trilogies not found.');
  process.exit(2);
}

const entries = [];
for (const slug of fs.readdirSync(DIR).sort()) {
  const slugDir = path.join(DIR, slug);
  if (!fs.statSync(slugDir).isDirectory()) continue;
  for (const frame of ['01', '02', '03']) {
    const file = path.join(slugDir, `${frame}.webp`);
    if (fs.existsSync(file)) entries.push({ slug, frame, key: `${slug}-${frame}` });
  }
}

const v = (key) => key.replace(/-/g, '_');

const header = `// AUTO-GENERATED by scripts/gen-trilogy-imports.mjs — do not edit by hand.
//
// Static image imports for the 20-trilogy photo set, so Next bundles all
// ${entries.length} frames into _next/static rather than serving them from public/.
//
// WHY THIS FILE EXISTS AT ALL
//
// This deployment does not serve apps/web/public. Measured, not assumed — see
// the identical note in data/illustration-images.ts, data/floor-images.ts and
// data/color-matching-images.ts, and F-131.
//
// A static import also carries its own intrinsic width and height on the
// imported object itself (StaticImageData.width / .height) — lib/trilogies.ts
// reads those directly rather than maintaining a second, driftable dims table.
//
// Regenerate with: node scripts/gen-trilogy-imports.mjs
import type { StaticImageData } from 'next/image';

`;

let out = header;
for (const { slug, frame, key } of entries) {
  out += `import ${v(key)} from '../../public/images/trilogies/${slug}/${frame}.webp';\n`;
}

out += `\nexport const TRILOGY_IMAGES: Record<string, StaticImageData> = {\n`;
for (const { key } of entries) out += `  '${key}': ${v(key)},\n`;
out += `};\n\n`;

out += `/** A static-imported trilogy frame, keyed '<slug>-01' | '<slug>-02' | '<slug>-03'. */
export const trilogyImage = (key: string): StaticImageData | undefined =>
  TRILOGY_IMAGES[key];
`;

fs.writeFileSync(OUT, out);
console.log(`✓ generated ${entries.length} static import(s) → ${path.relative(ROOT, OUT)}`);
