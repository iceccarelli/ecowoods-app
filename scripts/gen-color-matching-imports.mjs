#!/usr/bin/env node
/**
 * scripts/gen-color-matching-imports.mjs
 *
 * Regenerates apps/web/app/data/color-matching-images.ts from whatever is in
 * the five public/images/{color-matching,guides,species,services,case-studies}
 * folders, cross-referenced against scripts/fixtures/color-matching-manifest.csv
 * for alt text, captions, intrinsic size and primary placement.
 *
 * WHY STATIC IMPORTS AND NOT public/images/... URLS
 *
 * This deployment does not serve apps/web/public — see the identical note at
 * the top of data/illustration-images.ts and data/floor-images.ts, and
 * F-131. A file sitting in public/images/color-matching/foo.webp is a 404 on
 * the live site no matter how correctly it is committed; importing it makes
 * Next bundle the bytes into _next/static instead, which IS served.
 *
 * WHY THE MANIFEST AND NOT HAND-WRITTEN ALT TEXT
 *
 * Ecowoods' honesty rules (see the honesty-kernel skill) require every public
 * claim to trace to one named source. MANIFEST.csv is that source for this
 * image pack: it is the file the images were generated against, and it is
 * where "process, not a promise" language and "never exact match" language
 * already live. Copying it here — mechanically, via this script — means the
 * alt text and captions rendered on the site cannot drift from the record of
 * what each image was briefed to show.
 *
 *   node scripts/gen-color-matching-imports.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const MANIFEST = path.join(ROOT, 'scripts/fixtures/color-matching-manifest.csv');
const IMAGE_DIRS = ['color-matching', 'guides', 'species', 'services', 'case-studies'];
const PUBLIC_ROOT = path.join(ROOT, 'apps/web/public/images');
const OUT = path.join(ROOT, 'apps/web/app/data/color-matching-images.ts');

if (!fs.existsSync(MANIFEST)) {
  console.error(`gen-color-matching-imports: ${path.relative(ROOT, MANIFEST)} not found.`);
  process.exit(2);
}

/* Minimal CSV parser — the manifest has quoted fields containing commas, so a
   plain split(',') corrupts every alt/caption/prompt column. No dependency
   needed for eleven columns and ninety-four rows. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n') {
      if (field !== '' || row.length) {
        row.push(field);
        rows.push(row);
      }
      row = [];
      field = '';
    } else if (c === '\r') {
      // skip
    } else {
      field += c;
    }
  }
  if (field !== '' || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const csvRows = parseCsv(fs.readFileSync(MANIFEST, 'utf8'));
const header = csvRows[0];
const records = csvRows.slice(1).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));
const webpRows = records.filter((r) => r.format === 'webp');

/* Cross-check the manifest against the folders actually on disk, so this
   generator fails loudly instead of silently importing a subset. */
const onDisk = [];
for (const dir of IMAGE_DIRS) {
  const full = path.join(PUBLIC_ROOT, dir);
  if (!fs.existsSync(full)) continue;
  for (const f of fs.readdirSync(full)) {
    if (f.endsWith('.webp')) onDisk.push({ dir, id: f.replace(/\.webp$/, '') });
  }
}

const manifestIds = new Set(webpRows.map((r) => r.filename.replace(/\.webp$/, '')));
const diskIds = new Set(onDisk.map((f) => f.id));
const missingOnDisk = [...manifestIds].filter((id) => !diskIds.has(id));
const missingInManifest = [...diskIds].filter((id) => !manifestIds.has(id));
if (missingOnDisk.length || missingInManifest.length) {
  console.error('gen-color-matching-imports: manifest and disk disagree.');
  if (missingOnDisk.length) console.error('  in manifest, not on disk:', missingOnDisk.join(', '));
  if (missingInManifest.length) console.error('  on disk, not in manifest:', missingInManifest.join(', '));
  process.exit(2);
}

onDisk.sort((a, b) => a.id.localeCompare(b.id));

const v = (id) => id.replace(/-/g, '_');
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, ' ');

const header_ts = `// AUTO-GENERATED by scripts/gen-color-matching-imports.mjs — do not edit by hand.
//
// Static image imports for the colour-matching illustration pack, so Next
// bundles all ${onDisk.length} photoreal frames into _next/static rather than serving
// them from public/.
//
// WHY THIS FILE EXISTS AT ALL
//
// This deployment does not serve apps/web/public. Measured, not assumed — see
// the identical note in data/illustration-images.ts and data/floor-images.ts,
// and F-131. A file sitting in public/images/color-matching/foo.webp 404s on
// the live site no matter how correctly it is committed.
//
// WHERE THE ALT TEXT AND CAPTIONS COME FROM
//
// scripts/fixtures/color-matching-manifest.csv — the brief every one of these
// ${onDisk.length} images was generated against. Copied here mechanically by the
// generator so the words rendered on the site cannot drift from that record.
// Regenerate with: node scripts/gen-color-matching-imports.mjs
//
// A static import also carries its own intrinsic width and height, so
// next/image reserves the correct box without a component having to declare it.
import type { StaticImageData } from 'next/image';

`;

let out = header_ts;
for (const { dir, id } of onDisk) {
  out += `import ${v(id)} from '../../public/images/${dir}/${id}.webp';\n`;
}

out += `\nexport type ColorMatchMeta = {\n  /** public/images/<folder>/<id>.webp */\n  folder: string;\n  width: number;\n  height: number;\n  /** Describes the INFORMATION, not the picture. From MANIFEST.csv. */\n  alt: string;\n  /** Shown under the figure. From MANIFEST.csv. */\n  caption: string;\n  /** MANIFEST.csv's declared primary home for this frame. */\n  pageUrl: string;\n  section: string;\n};\n\n`;

out += `export const COLOR_MATCHING_IMAGES: Record<string, StaticImageData> = {\n`;
for (const { id } of onDisk) out += `  '${id}': ${v(id)},\n`;
out += `};\n\n`;

const metaById = new Map(webpRows.map((r) => [r.filename.replace(/\.webp$/, ''), r]));
out += `export const COLOR_MATCHING_META: Record<string, ColorMatchMeta> = {\n`;
for (const { dir, id } of onDisk) {
  const r = metaById.get(id);
  out += `  '${id}': {\n`;
  out += `    folder: '${dir}',\n`;
  out += `    width: ${Number(r.width)},\n`;
  out += `    height: ${Number(r.height)},\n`;
  out += `    alt: '${esc(r.alt_text)}',\n`;
  out += `    caption: '${esc(r.caption)}',\n`;
  out += `    pageUrl: '${esc(r.page_url)}',\n`;
  out += `    section: '${esc(r.section_on_page)}',\n`;
  out += `  },\n`;
}
out += `};\n\n`;

out += `/** A static-imported frame, or undefined if \`id\` is not in the pack. */
export const colorMatchingImage = (id: string): StaticImageData | undefined =>
  COLOR_MATCHING_IMAGES[id];

/**
 * Build a FigureRotator slide from a colour-matching frame. \`href\` is the
 * caller's choice (a case study, a guide) — the manifest's own \`pageUrl\` is
 * this frame's PRIMARY home, not necessarily the link a given rotator wants,
 * so it is never defaulted here silently.
 */
export const colorMatchingSlide = (
  id: string,
  href?: string,
): { id: string; src: StaticImageData; alt: string; caption: string; href?: string; width: number; height: number } | undefined => {
  const img = COLOR_MATCHING_IMAGES[id];
  const meta = COLOR_MATCHING_META[id];
  if (!img || !meta) return undefined;
  return { id, src: img, alt: meta.alt, caption: meta.caption, href, width: meta.width, height: meta.height };
};
`;

fs.writeFileSync(OUT, out);
console.log(`✓ generated ${onDisk.length} static import(s) → ${path.relative(ROOT, OUT)}`);
